const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  getApiKey: () => ipcRenderer.invoke('get-api-key'),
  saveApiKey: (apiKey) => ipcRenderer.invoke('save-api-key', apiKey),
  getGithubToken: () => ipcRenderer.invoke('get-github-token'),
  saveGithubToken: (token) => ipcRenderer.invoke('save-github-token', token),
  getModel: () => ipcRenderer.invoke('get-model'),
  saveModel: (model) => ipcRenderer.invoke('save-model', model),
  getAnalysisMode: () => ipcRenderer.invoke('get-analysis-mode'),
  saveAnalysisMode: (mode) => ipcRenderer.invoke('save-analysis-mode', mode),
  selectFile: () => ipcRenderer.invoke('select-file'),
  selectProject: () => ipcRenderer.invoke('select-project'),
  getFileStats: (filePath) => ipcRenderer.invoke('get-file-stats', filePath),
  getProjectStats: (projectPath) => ipcRenderer.invoke('get-project-stats', projectPath),
  findAgentScript: () => ipcRenderer.invoke('find-agent-script'),
  explainFile: (filePath, apiKey, model, analysisMode, githubUrl) => ipcRenderer.invoke('explain-file', filePath, apiKey, model, analysisMode, githubUrl),
  explainProject: (projectPath, apiKey, model, analysisMode, githubUrl) => ipcRenderer.invoke('explain-project', projectPath, apiKey, model, analysisMode, githubUrl),
  cancelAnalysis: () => ipcRenderer.invoke('cancel-analysis'),
  getTokenUsage: () => ipcRenderer.invoke('get-token-usage'),
  getTokenHistory: () => ipcRenderer.invoke('get-token-history'),
  resetTokenUsage: () => ipcRenderer.invoke('reset-token-usage'),
  getAvailableTokens: () => ipcRenderer.invoke('get-available-tokens'),
  addAvailableTokens: (amount) => ipcRenderer.invoke('add-available-tokens', amount),
  deductAvailableTokens: (amount) => ipcRenderer.invoke('deduct-available-tokens', amount),
  chatAboutCode: (question, codePath, codeType, apiKey, model, analysisMode, existingExplanation) => 
    ipcRenderer.invoke('chat-about-code', question, codePath, codeType, apiKey, model, analysisMode, existingExplanation),
  getTheme: () => ipcRenderer.invoke('get-theme'),
  saveTheme: (theme) => ipcRenderer.invoke('save-theme', theme),
  getLayout: () => ipcRenderer.invoke('get-layout'),
  saveLayout: (layout) => ipcRenderer.invoke('save-layout', layout),
  // GitHub API
  githubParseUrl: (url) => ipcRenderer.invoke('github-parse-url', url),
  githubRepoSummary: (url) => ipcRenderer.invoke('github-repo-summary', url),
  githubRepoReadme: (url) => ipcRenderer.invoke('github-repo-readme', url),
  githubRepoContributors: (url) => ipcRenderer.invoke('github-repo-contributors', url),
  githubRepoReleases: (url) => ipcRenderer.invoke('github-repo-releases', url),
  githubRepoLanguages: (url) => ipcRenderer.invoke('github-repo-languages', url),
  githubRepoRelated: (url) => ipcRenderer.invoke('github-repo-related', url),
  githubRepoAll: (url) => ipcRenderer.invoke('github-repo-all', url),
  githubRepoCommits: (url, page, perPage) => ipcRenderer.invoke('github-repo-commits', url, page, perPage),
  summarizeCommit: (url, sha, apiKey, model) => ipcRenderer.invoke('summarize-commit', url, sha, apiKey, model),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
});

